/* =========================================================
   7. TRANSLATE STATIC CONTENT
========================================================= */

function translatePage() {

    const elements =
        document.querySelectorAll("[data-lang]");


    elements.forEach(element => {

        const key =
            element.getAttribute("data-lang");


        if (
            translations[currentLanguage] &&
            translations[currentLanguage][key]
        ) {

            element.innerHTML =
                translations[currentLanguage][key];

        }

    });


    /* Update HTML language */

    document.documentElement.lang =
        currentLanguage;


    /* Update body language class */

    document.body.classList.remove(
        "lang-en",
        "lang-hi",
        "lang-gu"
    );

    document.body.classList.add(
        `lang-${currentLanguage}`
    );


    /* Update language button */

    const currentLanguageElement =
        document.getElementById("currentLanguage");


    if (currentLanguageElement) {

        const languageLabels = {

            en: "EN",
            hi: "हि",
            gu: "ગુ"

        };

        currentLanguageElement.textContent =
            languageLabels[currentLanguage];

    }


    /* Translate crop */

    const activeCropButton =
        document.querySelector(
            ".crop-tabs button.active"
        );


    if (activeCropButton) {

        updateCrop(
            activeCropButton.dataset.crop
        );

    }


    /* Translate finder result */

    updateFinder();

}


/* =========================================================
   8. LANGUAGE SWITCHING
========================================================= */

function setLanguage(language) {

    if (!translations[language]) {

        return;

    }


    currentLanguage =
        language;


    localStorage.setItem(
        "agriReuseLanguage",
        language
    );


    translatePage();

}


